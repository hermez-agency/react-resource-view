// Brings the documentation site (docs/) up to the latest Brand Assets: the
// Hermez style, theme and logo from its shadcn registry, and the project's own
// favicons and sharing card from hermez-agency/brand-assets.
//
// Only the site takes them. The library's src/styles.css is the theme it
// publishes, and stays as it is: the integrators keep their own palette.
//
// The shadcn CLI writes into a project with its own package.json, tsconfig and
// components.json, which docs/ has none of — so it runs in a throwaway project
// and what it wrote is copied over. Run with `pnpm run docs:sync-brand`.
import { execFileSync } from "node:child_process"
import {
  copyFileSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs"
import { Buffer } from "node:buffer"
import { tmpdir } from "node:os"
import { join, resolve } from "node:path"

const REGISTRY = "https://hermez.dev/brand-assets/r/{name}.json"
const ITEMS = ["@hermez/hermez", "@hermez/hermez-logo"]
const REPOSITORY = "hermez-agency/brand-assets"
const PROJECT_FILES = [
  "icon.svg",
  "favicon-32.png",
  "favicon-180.png",
  "favicon-512.png",
  "card.png",
]

const root = resolve(import.meta.dirname, "..")
const docs = join(root, "docs")
const bin = (name) => join(root, "node_modules", ".bin", name)

const response = await fetch(
  `https://api.github.com/repos/${REPOSITORY}/commits/main`,
  { headers: { accept: "application/vnd.github+json" } }
)
if (!response.ok) throw new Error(`GitHub answered ${response.status}`)
const commit = (await response.json()).sha.slice(0, 7)

const work = mkdtempSync(join(tmpdir(), "rrv-brand-assets-"))
try {
  writeFileSync(
    join(work, "package.json"),
    JSON.stringify({ name: "brand-assets-sync", private: true, type: "module" })
  )
  writeFileSync(
    join(work, "tsconfig.json"),
    JSON.stringify({
      compilerOptions: { baseUrl: ".", paths: { "@/*": ["./src/*"] } },
    })
  )
  writeFileSync(
    join(work, "components.json"),
    JSON.stringify({
      $schema: "https://ui.shadcn.com/schema.json",
      style: "base-luma",
      rsc: false,
      tsx: true,
      tailwind: {
        config: "",
        css: "src/hermez.css",
        baseColor: "neutral",
        cssVariables: true,
        prefix: "",
      },
      aliases: {
        components: "@/ui",
        ui: "@/ui",
        utils: "@/ui/cn",
        hooks: "@/ui/hooks",
        lib: "@/ui",
      },
      iconLibrary: "lucide",
      registries: { "@hermez": REGISTRY },
    })
  )
  mkdirSync(join(work, "src"))
  // The CLI needs a stylesheet to merge into; an empty one makes it fail.
  writeFileSync(join(work, "src", "hermez.css"), '@import "tailwindcss";\n')

  execFileSync(bin("shadcn"), ["add", ...ITEMS, "--yes", "--overwrite"], {
    cwd: work,
    stdio: ["ignore", "inherit", "inherit"],
  })

  // The style and its tokens. Tailwind is imported by docs/src/styles.css.
  const css = readFileSync(join(work, "src", "hermez.css"), "utf8").replace(
    '@import "tailwindcss";\n',
    ""
  )
  writeFileSync(
    join(docs, "src", "hermez.css"),
    `/*
 * The Hermez style, as Brand Assets' shadcn registry installs it
 * (${ITEMS.join(", ")}, ${REPOSITORY}@${commit}).
 * Generated by scripts/sync-brand-assets.mjs: do not edit, run
 * \`pnpm run docs:sync-brand\` instead.
 */
${css}`
  )

  // The logo: HermezMark and the SVG files. The utility `cn` the registry adds
  // too is the library's own, already at @/ui/cn.
  mkdirSync(join(docs, "src", "identity"), { recursive: true })
  copyFileSync(
    join(work, "src", "ui", "hermez-mark.tsx"),
    join(docs, "src", "identity", "hermez-mark.tsx")
  )
  mkdirSync(join(docs, "public", "hermez"), { recursive: true })
  for (const file of readdirSync(join(work, "public", "hermez"))) {
    copyFileSync(
      join(work, "public", "hermez", file),
      join(docs, "public", "hermez", file)
    )
  }

  // The fonts the style imports are packages of this repository, not of docs/.
  const wanted = JSON.parse(readFileSync(join(work, "package.json"), "utf8"))
  const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"))
  const have = { ...pkg.dependencies, ...pkg.devDependencies }
  const missing = Object.keys(wanted.dependencies ?? {}).filter(
    (name) => name.startsWith("@fontsource") && !have[name]
  )
  if (missing.length > 0) {
    console.warn(
      `\nMissing font packages, add them: pnpm add -D ${missing.join(" ")}`
    )
  }
} finally {
  rmSync(work, { recursive: true, force: true })
}

// The project's own visuals: favicons, icon and sharing card.
for (const file of PROJECT_FILES) {
  const url = `https://raw.githubusercontent.com/${REPOSITORY}/${commit}/projects/react-resource-view/${file}`
  const asset = await fetch(url)
  if (!asset.ok) throw new Error(`${url} answered ${asset.status}`)
  writeFileSync(join(docs, "public", file), Buffer.from(await asset.arrayBuffer()))
}

execFileSync(
  bin("prettier"),
  [
    "--write",
    join(docs, "src", "hermez.css"),
    join(docs, "src", "identity", "hermez-mark.tsx"),
  ],
  { stdio: "inherit" }
)

console.log(`\nDocs site synced with ${REPOSITORY}@${commit}.`)
